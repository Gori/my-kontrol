"""Convert monospace BDF fonts (ASCII 32..126) to a C header.

Glyphs are stored row by row, one byte per row, MSB = leftmost pixel.
usage: bdf2c.py out.h name=font.bdf [name=font.bdf ...]
"""
import sys

FIRST, LAST = 32, 126


def load(path):
    glyphs, fbb = {}, None
    lines = iter(open(path, encoding='latin-1').read().splitlines())
    for ln in lines:
        if ln.startswith('FONTBOUNDINGBOX'):
            fbb = list(map(int, ln.split()[1:]))
        elif ln.startswith('STARTCHAR'):
            enc = bbx = None
            for ln in lines:
                if ln.startswith('ENCODING'):
                    enc = int(ln.split()[1])
                elif ln.startswith('BBX'):
                    bbx = list(map(int, ln.split()[1:]))
                elif ln == 'BITMAP':
                    rows = []
                    for ln in lines:
                        if ln == 'ENDCHAR':
                            break
                        rows.append(int(ln, 16) >> (len(ln) * 4 - 8) if len(ln) > 2 else int(ln, 16))
                    glyphs[enc] = (bbx, rows)
                    break
    return fbb, glyphs


def cell(fbb, bbx, rows):
    fw, fh, fx, fy = fbb
    w, h, x, y = bbx
    out = [0] * fh
    top = (fh + fy) - (h + y)          # rows from cell top to glyph top
    for i, r in enumerate(rows):
        if 0 <= top + i < fh:
            out[top + i] = (r >> (x - fx)) & 0xFF if x >= fx else (r << (fx - x)) & 0xFF
    return out


out = open(sys.argv[1], 'w')
out.write('/* generated by tools/bdf2c.py from Spleen (BSD-2-Clause, (c) Frederic Cambus) */\n')
out.write('#pragma once\n#include "font.h"\n\n')
for spec in sys.argv[2:]:
    name, path = spec.split('=')
    fbb, glyphs = load(path)
    data = []
    for c in range(FIRST, LAST + 1):
        data += cell(fbb, *glyphs[c]) if c in glyphs else [0] * fbb[1]
    out.write(f'static const uint8_t {name}_data[] = {{\n')
    for i in range(0, len(data), fbb[1]):
        out.write('    ' + ', '.join(f'0x{v:02x}' for v in data[i:i + fbb[1]]) + f',  /* {chr(FIRST + i // fbb[1])!r} */\n')
    out.write(f'}};\n/* {name}: {fbb[0]}x{fbb[1]}, chars {FIRST}..{LAST} */\n\n')
print('ok')
