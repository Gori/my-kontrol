#!/usr/bin/env python3
"""Compiles a board's surface description (boards/<board>/surface.json) into
C: board_surface_json[], the minified ASCII JSON the keyboard sends in answer
to DESCRIBE (docs/protocol.md).

    surface2c.py boards/m32/surface.json build/m32/surface_json.c"""
import json
import sys

src, out = sys.argv[1:3]
with open(src, encoding='utf-8') as f:
    doc = json.load(f)
text = json.dumps(doc, ensure_ascii=True, separators=(',', ':'))
lines = [text[i:i + 96].replace('\\', '\\\\').replace('"', '\\"') for i in range(0, len(text), 96)]
with open(out, 'w') as f:
    f.write('/* generated by tools/surface2c.py from %s */\n' % src)
    f.write('const char board_surface_json[] =\n')
    for l in lines:
        f.write('    "%s"\n' % l)
    f.write('    ;\n')
