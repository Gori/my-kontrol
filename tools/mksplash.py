"""Render the boot splash into SSD1306 page format (128x32, LSB = top pixel).

usage: mksplash.py "Oskar's Firmware" ../firmware/splash.h [preview.png]
"""
import sys
from PIL import Image, ImageDraw, ImageFont

W, H = 128, 32
text, out = sys.argv[1], sys.argv[2]

img = Image.new('1', (W, H), 0)
draw = ImageDraw.Draw(img)
# largest bold Helvetica size that fits with a 2 px margin
for size in range(24, 6, -1):
    font = ImageFont.truetype('/System/Library/Fonts/Helvetica.ttc', size, index=1)
    l, t, r, b = draw.textbbox((0, 0), text, font=font)
    if r - l <= W - 4 and b - t <= H - 4:
        break
draw.text(((W - (r - l)) // 2 - l, (H - (b - t)) // 2 - t), text, font=font, fill=1)

px = img.load()
data = []
for page in range(H // 8):
    for x in range(W):
        data.append(sum(1 << bit for bit in range(8) if px[x, page * 8 + bit]))

with open(out, 'w') as f:
    f.write(f'/* generated by tools/mksplash.py: "{text}", Helvetica Bold {size}px */\n')
    f.write('#pragma once\n#include <stdint.h>\n\nstatic const uint8_t splash[512] = {\n')
    for i in range(0, len(data), 16):
        f.write('    ' + ', '.join(f'0x{v:02x}' for v in data[i:i + 16]) + ',\n')
    f.write('};\n')
if len(sys.argv) > 3:
    img.resize((W * 4, H * 4)).save(sys.argv[3])
print('font size', size)
