"""Velocity table: index = time between the two key contacts in 200 us units
(after black/white travel compensation), value = MIDI velocity 1..127.
Logarithmic between T_FAST (127) and T_SLOW (1).

usage: mkvelocity.py ../firmware/vel_table.h
"""
import math
import sys

T_FAST, T_SLOW = 4.0, 51.0  # ms; matches the stock firmware's 20..255 tick range
rows = []
for i in range(256):
    t = max(i * 0.2, 1e-3)
    if t <= T_FAST:
        v = 127
    elif t >= T_SLOW:
        v = 1
    else:
        v = round(1 + 126 * (math.log(T_SLOW) - math.log(t)) / (math.log(T_SLOW) - math.log(T_FAST)))
    rows.append(v)

with open(sys.argv[1], 'w') as f:
    f.write(f'/* generated by tools/mkvelocity.py: log curve, {T_FAST} ms -> 127, {T_SLOW} ms -> 1 */\n')
    f.write('#pragma once\n#include <stdint.h>\n\nstatic const uint8_t vel_table[256] = {\n')
    for i in range(0, 256, 16):
        f.write('    ' + ', '.join(f'{v:3d}' for v in rows[i:i + 16]) + ',\n')
    f.write('};\n')
print('ok', rows[20], rows[64], rows[128], rows[255])
